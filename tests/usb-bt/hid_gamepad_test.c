static struct gpsp_hid_gamepad s_pad;

static void init(const uint8_t *descriptor, size_t size, bool sony,
        enum gpsp_hid_gamepad_result expected)
{
    assert(gpsp_hid_gamepad_init(&s_pad, descriptor, size, sony ?
            GPSP_HID_LAYOUT_SONY : GPSP_HID_LAYOUT_SEQUENTIAL) == expected);
}

static unsigned decode(const uint8_t *report, size_t size)
{
    unsigned buttons = 0xdeadbeef;

    assert(gpsp_hid_gamepad_decode(&s_pad, report, size, &buttons));
    return buttons;
}

static bool rejected(const uint8_t *report, size_t size)
{
    unsigned buttons = 0xdeadbeef;

    return !gpsp_hid_gamepad_decode(&s_pad, report, size, &buttons) &&
            buttons == 0xdeadbeef;
}

int main(void)
{
    init(s_android, sizeof(s_android), false, GPSP_HID_GAMEPAD_OK);
    assert(s_pad.report_ids && s_pad.layout == GPSP_HID_LAYOUT_SEQUENTIAL);
    const uint8_t android[] = {0x01, 0x02, 0x08, 0x02, 0x80, 0x00};
    assert(decode(android, sizeof(android)) ==
            (BIT(A) | BIT(R3) | BIT(RIGHT) | BIT(UP)));
    /* Button numbers past the table, such as 13, are not taken as Home. */
    const uint8_t android_more[] = {0x01, 0x15, 0x50, 0x08, 0xff, 0x80};
    assert(s_pad.dropped == 3);
    assert(decode(android_more, sizeof(android_more)) ==
            (BIT(B) | BIT(Y) | BIT(L) | BIT(RIGHT)));
    assert(rejected(android, sizeof(android) - 1));
    const uint8_t other_id[] = {0x02, 0, 0, 0, 0, 0};
    assert(rejected(other_id, sizeof(other_id)));
    assert(rejected(android, 0));

    init(s_sequential, sizeof(s_sequential), false, GPSP_HID_GAMEPAD_OK);
    assert(!s_pad.report_ids && s_pad.layout == GPSP_HID_LAYOUT_SEQUENTIAL);
    const uint8_t left[] = {0x00, 0x80, 0x00, 0x00, 0x00, 0x01, 0x01};
    assert(decode(left, sizeof(left)) == (BIT(LEFT) | BIT(B) | BIT(SELECT)));
    const uint8_t down_right[] = {0xff, 0x7f, 0x00, 0x40, 0x04, 0x0c, 0x02};
    assert(decode(down_right, sizeof(down_right)) ==
            (BIT(RIGHT) | BIT(DOWN) | BIT(Y) | BIT(X) | BIT(START)));
    const uint8_t center[] = {0x00, 0x10, 0x00, 0xf0, 0x01, 0x00, 0x00};
    assert(decode(center, sizeof(center)) == BIT(UP));
    puts("HID_GAMEPAD layouts, hats, signed axes, and dead zones: pass");

    init(s_reports, sizeof(s_reports), false, GPSP_HID_GAMEPAD_OK);
    const uint8_t buttons[] = {0x01, 0x02}, dpad[] = {0x02, 0x19}, idle[] = {0x02, 0x00};
    assert(decode(buttons, sizeof(buttons)) == BIT(A));
    assert(decode(dpad, sizeof(dpad)) == (BIT(A) | BIT(UP) | BIT(LEFT) | HOME));
    assert(decode(idle, sizeof(idle)) == BIT(A));
    gpsp_hid_gamepad_reset(&s_pad);
    assert(decode(idle, sizeof(idle)) == 0);
    puts("HID_GAMEPAD report IDs keep separate state: pass");

    init(s_array, sizeof(s_array), false, GPSP_HID_GAMEPAD_OK);
    const uint8_t array[] = {0x02, 0x00}, both[] = {0x0a, 0x0d};
    assert(decode(array, sizeof(array)) == BIT(A));
    assert(decode(both, sizeof(both)) == BIT(START));
    init(s_sixteen, sizeof(s_sixteen), false, GPSP_HID_GAMEPAD_OK);
    const uint8_t nintendo[] = {0x05, 0x10};
    assert(decode(nintendo, sizeof(nintendo)) == (BIT(B) | BIT(Y)));
    init(s_sixteen, sizeof(s_sixteen), true, GPSP_HID_GAMEPAD_OK);
    assert(s_pad.layout == GPSP_HID_LAYOUT_SONY);
    const uint8_t sony[] = {0x07, 0x10};
    assert(decode(sony, sizeof(sony)) == (BIT(Y) | BIT(B) | BIT(A) | HOME));
    puts("HID_GAMEPAD button arrays and vendor layouts: pass");

    init(s_keyboard, sizeof(s_keyboard), false, GPSP_HID_GAMEPAD_NOT_GAMEPAD);
    init(s_no_controls, sizeof(s_no_controls), false, GPSP_HID_GAMEPAD_NOT_GAMEPAD);
    init(s_combo, sizeof(s_combo), false, GPSP_HID_GAMEPAD_OK);
    const uint8_t key[] = {0x01, 0xff, 0x01}, pad[] = {0x02, 0x03};
    assert(rejected(key, sizeof(key)));
    assert(decode(pad, sizeof(pad)) == (BIT(B) | BIT(A)));
    init(s_relative, sizeof(s_relative), false, GPSP_HID_GAMEPAD_OK);
    const uint8_t moved[] = {0x7f, 0x00, 0x01};
    assert(s_pad.field_count == 1 && decode(moved, sizeof(moved)) == BIT(B));
    init(s_huge, sizeof(s_huge), false, GPSP_HID_GAMEPAD_OK);
    assert(s_pad.field_count == 12);
    init(s_many, sizeof(s_many), false, GPSP_HID_GAMEPAD_OK);
    const uint8_t many[] = {0, 0, 0, 0, 0, 0x04};
    assert(s_pad.field_count == 13 && decode(many, sizeof(many)) == BIT(DOWN));
    /* Values outside the logical range are null. */
    init(s_null, sizeof(s_null), false, GPSP_HID_GAMEPAD_OK);
    const uint8_t null_x[] = {0x80, 0x03}, right[] = {0x7f, 0x01};
    assert(decode(null_x, sizeof(null_x)) == 0);
    assert(decode(right, sizeof(right)) == (BIT(RIGHT) | BIT(B)));
    init(s_truncated, sizeof(s_truncated), false, GPSP_HID_GAMEPAD_MALFORMED);
    init(s_unclosed, sizeof(s_unclosed), false, GPSP_HID_GAMEPAD_MALFORMED);
    init(s_mixed_ids, sizeof(s_mixed_ids), false, GPSP_HID_GAMEPAD_MALFORMED);
    init(NULL, 0, false, GPSP_HID_GAMEPAD_MALFORMED);
    for (size_t i = 0; i < sizeof(s_android); i++)
        gpsp_hid_gamepad_init(&s_pad, s_android, i, GPSP_HID_LAYOUT_SEQUENTIAL);
    puts("HID_GAMEPAD keyboards, relative axes, null values, bounds, and malformed descriptors: pass");
    puts("HID_GAMEPAD PASS");
    return 0;
}
